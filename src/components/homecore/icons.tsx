function hasHaIcon() {
    return typeof customElements !== 'undefined' && Boolean(customElements.get('ha-icon'));
}

/** A light's glyph: the drawn shape when we have it, otherwise HA's own icon, otherwise a bulb. */
export function HcGlyph({ icon }: { icon: string }) {
    const path = GLYPH_PATHS[icon];
    if (!path && hasHaIcon()) {
        return <ha-icon icon={icon} className="hcGlyph" />;
    }

    return (
        <svg className="hcGlyph" viewBox="0 0 24 24" aria-hidden="true">
            <path d={path ?? GLYPH_PATHS['mdi:lightbulb']} />
        </svg>
    );
}

